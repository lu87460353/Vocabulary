def get_translation(word):
    """查找单词的中文释义（增强匹配）"""
    word_lower = word.lower().strip()
    
    # 直接匹配
    if word_lower in CORE_DICT:
        return CORE_DICT[word_lower]
    if word.strip() in CORE_DICT:
        return CORE_DICT[word.strip()]
    
    # 尝试各种清理
    cleaners = [
        lambda w: w.split('(')[0].strip(),
        lambda w: w.split('（')[0].strip(),
        lambda w: w.split('/')[0].strip(),
        lambda w: w.split('=')[0].strip(),
        lambda w: w.replace('=', '').replace('(', '').replace(')', '').strip(),
        lambda w: ' '.join(w.split()),
    ]
    
    for cleaner in cleaners:
        cleaned = cleaner(word_lower)
        if cleaned and cleaned in CORE_DICT:
            return CORE_DICT[cleaned]
        # also try original case version
        cleaned_orig = cleaner(word.strip())
        if cleaned_orig and cleaned_orig in CORE_DICT:
            return CORE_DICT[cleaned_orig]
    
    # 尝试部分匹配
    parts = word_lower.split()
    if len(parts) > 1:
        for n in range(len(parts), 1, -1):
            short = ' '.join(parts[:n])
            if short in CORE_DICT:
                return CORE_DICT[short]
    
    return "暂无释义（可自行添加）"

def load_dict_to_db():
    """将内置词典加载到数据库"""
    from database import get_db
    conn = get_db()
    for word, trans in CORE_DICT.items():
        conn.execute('UPDATE words SET translation=? WHERE word=?', (trans, word))
    conn.commit()
    conn.close()

